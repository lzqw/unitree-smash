"""Deterministic contact-first trajectory search for jump-and-hit motion.

This module is a small, causal planner for the Approach teacher.  It follows
the useful part of the ball-bumping formulation in arXiv:2210.05195: solve a
time/state terminal condition for the hit first, then let the existing
whole-body controller track that reference.  It deliberately does not search
the landing phase.

The planner is kinematic at the arm level.  A caller may attach the existing
full-body predictor as ``evaluator``; a candidate is executable only when that
evaluator accepts the complete pre-contact prefix.  No TRAIN case, future
trajectory, or learned action is used here.
"""
from dataclasses import dataclass
from collections import Counter
import math
from typing import Callable, Optional

import numpy as np
from .inverse_impact_target_v1 import UnreachableImpactTarget


@dataclass(frozen=True)
class ContactFirstSearchConfig:
    """Bounded deterministic candidate contract.

    The small grid searches contact timing and contact-speed scale, while the
    six-joint increments are generated by the measured racket Jacobian.  The
    suffix after contact is a held endpoint and is not part of contact-first
    acceptance.
    """

    require_joint_prefix: bool = False
    evaluate_impact_outcome: bool = False
    inverse_impact_targets: bool = False
    bounded_replanning: bool = False
    position_anchored_search: bool = False
    velocity_aware_pose: bool = False
    # Offline only: retarget joint rates against actual analytic task outcome.
    # No physical velocity or ball-side acceptance threshold is relaxed.
    impact_feasible_rate_retarget: bool = False
    reachable_impact_targets: bool = False
    dt_s: float = 0.01
    # Approach planning starts around t=2.0 s while contact is commonly near
    # 2.7 s in the current DTG contract; 96 x 10 ms covers that interval.
    # Recovery's independent 32-node protocol is unchanged.
    horizon_steps: int = 96
    contact_time_offsets_s: tuple = (-0.02, 0.0, 0.02)
    velocity_scales: tuple = (0.8, 1.0, 1.2)
    # Small tangent-plane face adjustments let the planner trade a nominal
    # normal that is unreachable at the selected arm posture for a nearby
    # physically realizable racket face.  The deviation is bounded and is
    # still scored against the selected contact normal; it is not a relaxed
    # normal residual gate.
    normal_tangent_offsets_rad: tuple = (
        (0.0, 0.0), (-0.20, 0.0), (0.20, 0.0), (0.0, -0.20), (0.0, 0.20))
    # The racket normal has only two independent orientation coordinates, so a
    # six-joint arm normally retains one local nullspace direction.  Exploring
    # a few bounded posture offsets lets the same contact task use a less
    # saturated joint without changing the task target or physical limits.
    nullspace_offsets_rad: tuple = (-0.12, -0.06, 0.06, 0.12)
    damping: float = 0.04
    normal_weight: float = 0.30
    normal_rate_gain: float = 2.0
    arm_velocity_limit_rad_s: float = 5.0
    # Public finite differences can contain contact/solver spikes.  These
    # bounds protect the causal base prediction from turning one noisy tick
    # into an impossible future racket velocity; they are not robot limits.
    base_linear_acceleration_limit_m_s2: float = 12.0
    base_angular_acceleration_limit_rad_s2: float = 4.0
    # Five bounded re-linearizations materially improve nonlinear FK
    # convergence while remaining sub-2 ms on the CPU benchmark path.
    kinematic_iterations: int = 5
    max_iteration_step_rad: float = 0.25
    handoff_duration_s: float = 0.02
    position_tolerance_m: float = 0.035
    normal_tolerance: float = 0.12
    velocity_tolerance_m_s: float = 0.75
    minimum_contact_speed_m_s: float = 0.25
    minimum_contact_speed_alignment: float = 0.15
    allow_reachable_velocity_projection: bool = True
    adaptive_normal_target_max_deviation_rad: float = 1.20
    # Rank feasible candidates by margin to the original physical velocity and
    # one-tick step limits.  These are ranking terms only; the hard gates
    # above still reject every violating sequence.
    speed_margin_weight: float = 0.15
    step_margin_weight: float = 0.10
    nullspace_penalty_weight: float = 0.01

    def validate(self):
        if not math.isfinite(self.dt_s) or self.dt_s <= 0.0:
            raise ValueError("Positive planner timestep required")
        if self.horizon_steps < 2:
            raise ValueError("At least two trajectory nodes required")
        for name in ("contact_time_offsets_s", "velocity_scales", "nullspace_offsets_rad"):
            values = tuple(float(x) for x in getattr(self, name))
            if name != "nullspace_offsets_rad" and not values:
                raise ValueError(f"Finite {name} required")
            if not all(math.isfinite(x) for x in values):
                raise ValueError(f"Finite {name} required")
        normal_offsets = tuple(getattr(self, "normal_tangent_offsets_rad"))
        if not normal_offsets:
            raise ValueError("At least one normal tangent offset is required")
        for offset in normal_offsets:
            if len(offset) != 2 or not all(math.isfinite(float(x)) for x in offset):
                raise ValueError("Normal tangent offsets must be finite pairs")
        if self.damping <= 0.0 or self.normal_weight <= 0.0:
            raise ValueError("Positive task damping and normal weight required")
        for name in ("speed_margin_weight", "step_margin_weight",
                     "nullspace_penalty_weight"):
            value = float(getattr(self, name))
            if not math.isfinite(value) or value < 0.0:
                raise ValueError(f"Nonnegative finite {name} required")
        for name in ("minimum_contact_speed_m_s", "minimum_contact_speed_alignment"):
            value = float(getattr(self, name))
            if not math.isfinite(value) or value < 0.0:
                raise ValueError(f"Nonnegative finite {name} required")
        if self.minimum_contact_speed_alignment > 1.0:
            raise ValueError("Contact speed alignment must be at most one")
        for flag in ("position_anchored_search", "velocity_aware_pose",
                     "impact_feasible_rate_retarget"):
            if type(getattr(self, flag)) is not bool:
                raise ValueError(f"{flag} must be boolean")
        if self.impact_feasible_rate_retarget and not self.position_anchored_search:
            raise ValueError("Impact-feasible rate requires position-anchored search")
        if type(self.allow_reachable_velocity_projection) is not bool:
            raise ValueError("Velocity projection switch must be boolean")
        if (not math.isfinite(self.adaptive_normal_target_max_deviation_rad) or
                not 0.0 <= self.adaptive_normal_target_max_deviation_rad <= math.pi):
            raise ValueError("Adaptive normal target deviation must be in [0, pi]")
        if not math.isfinite(self.arm_velocity_limit_rad_s) or self.arm_velocity_limit_rad_s <= 0.0:
            raise ValueError("Positive arm velocity limit required")
        for name in ("base_linear_acceleration_limit_m_s2",
                     "base_angular_acceleration_limit_rad_s2"):
            value = float(getattr(self, name))
            if not math.isfinite(value) or value <= 0.0:
                raise ValueError(f"Positive finite {name} required")
        if self.kinematic_iterations < 1 or self.kinematic_iterations > 8:
            raise ValueError("Kinematic iterations must be in [1, 8]")
        if not math.isfinite(self.max_iteration_step_rad) or self.max_iteration_step_rad <= 0.0:
            raise ValueError("Positive kinematic iteration step required")
        if not math.isfinite(self.handoff_duration_s) or not 0.0 <= self.handoff_duration_s <= 0.2:
            raise ValueError("Handoff duration must be in [0, 0.2] seconds")
        return self


@dataclass(frozen=True)
class BallisticContactEvent:
    time_s: float
    position_world_m: np.ndarray
    velocity_world_m_s: np.ndarray


@dataclass
class ContactFirstCandidate:
    """A candidate arm trajectory and its contact-prefix diagnostics."""

    q_rad: np.ndarray
    qd_rad_s: np.ndarray
    contact_index: int
    contact_time_s: float
    score: float
    position_error_m: float
    normal_error: float
    velocity_error_m_s: float
    metadata: dict


def solve_ballistic_plane_contact(position_world_m, velocity_world_m_s,
                                  plane_point_world_m, plane_normal_world,
                                  gravity_world=(0.0, 0.0, -9.81),
                                  min_time_s=0.0, max_time_s=2.0):
    """Solve the first descending ballistic crossing of a contact plane.

    DTG's existing drag-aware ``predict_initial_intercept`` remains the
    preferred production event source.  This helper supplies the paper-style
    low-cost time/state fallback and is useful for CPU validation.
    """
    p = np.asarray(position_world_m, dtype=float)
    v = np.asarray(velocity_world_m_s, dtype=float)
    plane = np.asarray(plane_point_world_m, dtype=float)
    normal = np.asarray(plane_normal_world, dtype=float)
    gravity = np.asarray(gravity_world, dtype=float)
    if any(x.shape != (3,) for x in (p, v, plane, normal, gravity)):
        raise ValueError("Ballistic contact vectors must be 3D")
    if not all(np.isfinite(x).all() for x in (p, v, plane, normal, gravity)):
        raise ValueError("Finite ballistic contact vectors required")
    norm = np.linalg.norm(normal)
    if norm < 1e-9:
        raise ValueError("Nonzero contact-plane normal required")
    normal = normal / norm
    c = float(normal @ (p - plane))
    b = float(normal @ v)
    a = 0.5 * float(normal @ gravity)
    if abs(a) < 1e-10:
        roots = [] if abs(b) < 1e-10 else [-c / b]
    else:
        discriminant = b * b - 4.0 * a * c
        if discriminant < 0.0:
            return None
        root = math.sqrt(max(discriminant, 0.0))
        roots = [(-b - root) / (2.0 * a), (-b + root) / (2.0 * a)]
    roots = sorted(t for t in roots if min_time_s <= t <= max_time_s)
    for time_s in roots:
        velocity = v + gravity * time_s
        # Descending means motion is toward the negative normal side at hit.
        if float(normal @ velocity) <= 0.0:
            return BallisticContactEvent(
                time_s=float(time_s),
                position_world_m=p + v * time_s + 0.5 * gravity * time_s * time_s,
                velocity_world_m_s=velocity,
            )
    return None


def _validate_vectors(q, qd, position_jacobian, normal_jacobian,
                      racket_position, racket_normal, target_position,
                      target_normal, target_velocity, base_linear_velocity,
                      base_linear_acceleration, base_angular_velocity,
                      base_angular_acceleration, racket_offset, lower, upper,
                      velocity_limits):
    q = np.asarray(q, dtype=float)
    qd = np.asarray(qd, dtype=float)
    jp = np.asarray(position_jacobian, dtype=float)
    jn = np.asarray(normal_jacobian, dtype=float)
    vectors = [racket_position, racket_normal, target_position, target_normal,
               target_velocity, base_linear_velocity, base_linear_acceleration,
               base_angular_velocity, base_angular_acceleration, racket_offset]
    vectors = [np.asarray(x, dtype=float) for x in vectors]
    lower = np.asarray(lower, dtype=float)
    upper = np.asarray(upper, dtype=float)
    velocity_limits = np.asarray(velocity_limits, dtype=float)
    if q.shape != (6,) or qd.shape != (6,):
        raise ValueError("Six arm joint positions and velocities required")
    if jp.shape != (3, 6) or jn.shape != (3, 6):
        raise ValueError("Position and normal Jacobians must be 3x6")
    if any(x.shape != (3,) for x in vectors):
        raise ValueError("Contact vectors must be 3D")
    if lower.shape != (6,) or upper.shape != (6,) or velocity_limits.shape != (6,):
        raise ValueError("Six-joint bounds and velocity limits required")
    if np.any(upper <= lower) or np.any(velocity_limits <= 0.0):
        raise ValueError("Strict joint and velocity bounds required")
    if not all(np.isfinite(x).all() for x in [q, qd, jp, jn, *vectors,
                                               lower, upper, velocity_limits]):
        raise ValueError("Finite contact search inputs required")
    return (q, qd, jp, jn, *vectors, lower, upper, velocity_limits)


def _damped_inverse(matrix, damping):
    return matrix.T @ np.linalg.solve(matrix @ matrix.T + damping * damping *
                                      np.eye(matrix.shape[0]), np.eye(matrix.shape[0]))


def _validate_rotation(rotation, name="rotation_current_from_future"):
    rotation = np.asarray(rotation, dtype=float)
    if rotation.shape != (3, 3) or not np.isfinite(rotation).all():
        raise ValueError(f"{name} must be a finite 3x3 matrix")
    if not np.allclose(rotation.T @ rotation, np.eye(3), atol=2e-4, rtol=2e-4):
        raise ValueError(f"{name} must be orthonormal")
    determinant = float(np.linalg.det(rotation))
    if not math.isfinite(determinant) or determinant <= 0.0 or abs(determinant - 1.0) > 2e-4:
        raise ValueError(f"{name} must be a proper rotation")
    return rotation


def rotation_current_from_future_from_rotvec(rotvec):
    """Return a proper rotation from a causal body-frame rotation vector.

    The returned matrix maps future-base vectors into the current planning
    frame.  Rodrigues integration is sufficient for the short contact prefix
    and avoids introducing a quaternion convention into the planner API.
    """
    rotvec = np.asarray(rotvec, dtype=float)
    if rotvec.shape != (3,) or not np.isfinite(rotvec).all():
        raise ValueError("Finite 3D rotation vector required")
    angle = float(np.linalg.norm(rotvec))
    if angle < 1e-10:
        return np.eye(3)
    axis = rotvec / angle
    x, y, z = axis
    skew = np.array([[0., -z, y], [z, 0., -x], [-y, x, 0.]])
    rotation = np.eye(3) + math.sin(angle) * skew + (1. - math.cos(angle)) * (skew @ skew)
    return _validate_rotation(rotation)


def _normal_tangent_basis(normal):
    normal = np.asarray(normal, dtype=float)
    reference = np.array([0., 0., 1.])
    if abs(float(normal @ reference)) > 0.9:
        reference = np.array([1., 0., 0.])
    tangent_u = np.cross(reference, normal)
    tangent_u /= max(float(np.linalg.norm(tangent_u)), 1e-12)
    tangent_v = np.cross(normal, tangent_u)
    tangent_v /= max(float(np.linalg.norm(tangent_v)), 1e-12)
    return tangent_u, tangent_v


def _hermite(q0, qd0, q1, qd1, duration_s, times_s):
    s = np.clip(np.asarray(times_s, dtype=float) / duration_s, 0.0, 1.0)
    h00 = 2.0 * s**3 - 3.0 * s**2 + 1.0
    h10 = s**3 - 2.0 * s**2 + s
    h01 = -2.0 * s**3 + 3.0 * s**2
    h11 = s**3 - s**2
    q = (h00[:, None] * q0 + h10[:, None] * duration_s * qd0 +
         h01[:, None] * q1 + h11[:, None] * duration_s * qd1)
    dh00 = 6.0 * s**2 - 6.0 * s
    dh10 = 3.0 * s**2 - 4.0 * s + 1.0
    dh01 = -6.0 * s**2 + 6.0 * s
    dh11 = 3.0 * s**2 - 2.0 * s
    qd = (dh00[:, None] * q0 + dh10[:, None] * duration_s * qd0 +
          dh01[:, None] * q1 + dh11[:, None] * duration_s * qd1) / duration_s
    return q, qd


class ContactFirstTrajectorySearchV1:
    """Low-dimensional, deterministic contact-prefix search.

    ``evaluator`` receives ``(q_rad, qd_rad_s, contact_index, metadata)`` and
    must return either ``True`` or a mapping with ``accepted``.  It should use
    the existing full-body predictor when available.  Without an evaluator,
    this class performs only the causal kinematic and actuator precheck.
    """

    def __init__(self, config=None):
        self.config = (config or ContactFirstSearchConfig()).validate()
        self.last_diagnostics = {}

    def plan(self, *, q_rad, qd_rad_s, position_jacobian, normal_jacobian,
             racket_position_world_m, racket_normal_world,
             target_position_world_m, target_normal_world, target_velocity_world_m_s,
             contact_time_s, base_linear_velocity_world_m_s=(0.0, 0.0, 0.0),
             base_linear_acceleration_world_m_s2=(0.0, 0.0, 0.0),
             base_angular_velocity_world_rad_s=(0.0, 0.0, 0.0),
             base_angular_acceleration_world_rad_s2=(0.0, 0.0, 0.0),
             racket_offset_world_m=(0.0, 0.0, 0.0), lower_rad, upper_rad,
             velocity_limits_rad_s, evaluator: Optional[Callable] = None,
             kinematics_fn: Optional[Callable] = None,
             kinematics_at_time_fn: Optional[Callable] = None,
             target_state_fn: Optional[Callable] = None,
             base_state_fn: Optional[Callable] = None,
             impact_evaluator: Optional[Callable] = None):
        if self.config.require_joint_prefix and evaluator is None:
            raise ValueError("Joint prefix requires physical evaluator")
        data = _validate_vectors(
            q_rad, qd_rad_s, position_jacobian, normal_jacobian,
            racket_position_world_m, racket_normal_world,
            target_position_world_m, target_normal_world,
            target_velocity_world_m_s, base_linear_velocity_world_m_s,
            base_linear_acceleration_world_m_s2,
            base_angular_velocity_world_rad_s,
            base_angular_acceleration_world_rad_s2, racket_offset_world_m,
            lower_rad, upper_rad, velocity_limits_rad_s)
        (q0, qd0, jp, jn, racket_pos, racket_normal, target_pos,
         target_normal, target_velocity, base_linear,
         base_linear_acceleration, base_angular, base_angular_acceleration,
         racket_offset, lower, upper,
         velocity_limits) = data
        cfg = self.config
        requested_contact = float(contact_time_s)
        if not math.isfinite(requested_contact) or requested_contact <= cfg.dt_s:
            raise ValueError("Positive contact time after current state required")
        if target_state_fn is not None and not callable(target_state_fn):
            raise TypeError("target_state_fn must be callable or None")
        if base_state_fn is not None and not callable(base_state_fn):
            raise TypeError("base_state_fn must be callable or None")
        racket_normal = racket_normal / max(np.linalg.norm(racket_normal), 1e-12)
        target_normal = target_normal / max(np.linalg.norm(target_normal), 1e-12)
        target_normal_default = target_normal.copy()
        target_velocity_default = target_velocity.copy()
        # The target arrives from the public body-frame command.  During a
        # jump the base translates before contact, so solve the arm terminal
        # task in the predicted contact frame.  This is a causal constant-
        # acceleration extrapolation from the current measured base velocity
        # and acceleration; it does not read future simulator state.  The
        # velocity compensation below remains separate and is applied once.
        raw_base_linear_acceleration = base_linear_acceleration.copy()
        raw_base_angular_acceleration = base_angular_acceleration.copy()
        base_linear_acceleration = np.clip(
            base_linear_acceleration,
            -cfg.base_linear_acceleration_limit_m_s2,
            cfg.base_linear_acceleration_limit_m_s2)
        base_angular_acceleration = np.clip(
            base_angular_acceleration,
            -cfg.base_angular_acceleration_limit_rad_s2,
            cfg.base_angular_acceleration_limit_rad_s2)
        active_time=requested_contact
        if kinematics_at_time_fn is not None:
            def kinematics_fn(q):return kinematics_at_time_fn(q,active_time)
        target_metadata_cache={}
        target_state_cache = {}
        incoming_velocity_cache = {}
        base_state_cache = {}

        def target_state_at(duration_s):
            """Resolve a causal ball state for one candidate contact time."""
            cache_key = round(float(duration_s), 9)
            if cache_key in target_state_cache:
                cached = target_state_cache[cache_key]
                return tuple(value.copy() for value in cached)
            if target_state_fn is None:
                resolved = (target_pos.copy(), target_normal_default.copy(),
                            target_velocity_default.copy())
                target_state_cache[cache_key] = resolved
                return tuple(value.copy() for value in resolved)
            value = target_state_fn(float(duration_s))
            if isinstance(value, dict):
                target_metadata_cache[cache_key]={k:value[k] for k in
                    ('contact_point_local','optimized_q_rad','reachability',
                     'original_requested_racket_velocity_world_m_s','optimized_requested_racket_velocity_world_m_s',
                     'original_requested_velocity_current_frame_m_s',
                     'desired_outgoing_velocity_world_m_s',
                     'inverse_accepted_semantics','inverse_robot_kinematic_valid') if k in value}
                incoming = value.get("incoming_ball_velocity_world_m_s")
                if incoming is not None:
                    incoming = np.asarray(incoming, dtype=float)
                    if incoming.shape != (3,) or not np.isfinite(incoming).all():
                        raise ValueError("Incoming ball velocity must be a finite 3D vector")
                    incoming_velocity_cache[cache_key] = incoming.copy()
                candidate_position = value.get("position_world_m")
                candidate_velocity = value.get("velocity_world_m_s")
                candidate_normal = value.get("normal_world", target_normal_default)
            elif isinstance(value, (tuple, list)) and len(value) in (2, 3):
                candidate_position, candidate_velocity = value[:2]
                candidate_normal = value[2] if len(value) == 3 else target_normal_default
            else:
                raise ValueError(
                    "target_state_fn must return a mapping or (position, velocity[, normal])")
            candidate_position = np.asarray(candidate_position, dtype=float)
            candidate_velocity = np.asarray(candidate_velocity, dtype=float)
            candidate_normal = np.asarray(candidate_normal, dtype=float)
            if (candidate_position.shape != (3,) or candidate_velocity.shape != (3,) or
                    candidate_normal.shape != (3,) or
                    not all(np.isfinite(x).all() for x in (
                        candidate_position, candidate_velocity, candidate_normal))):
                raise ValueError("target_state_fn returned invalid finite 3D vectors")
            norm = float(np.linalg.norm(candidate_normal))
            if norm < 1e-9:
                raise ValueError("target_state_fn returned a zero normal")
            resolved = (candidate_position, candidate_normal / norm, candidate_velocity)
            target_state_cache[cache_key] = resolved
            return tuple(value.copy() for value in resolved)

        def base_state_at(duration_s):
            """Resolve the future base pose in the current planning frame.

            ``rotation_current_from_future`` maps a vector in the future base
            frame into the current planning frame.  Translation, linear
            velocity, and angular velocity use the current planning frame.
            This keeps body-frame observations from being silently treated as
            world-frame quantities.
            """
            cache_key = round(float(duration_s), 9)
            if cache_key in base_state_cache:
                cached = base_state_cache[cache_key]
                return tuple(value.copy() for value in cached)
            if base_state_fn is None:
                duration = float(duration_s)
                resolved = (
                    np.eye(3),
                    base_linear * duration + 0.5 * base_linear_acceleration * duration ** 2,
                    base_linear + base_linear_acceleration * duration,
                    base_angular + base_angular_acceleration * duration,
                )
            else:
                value = base_state_fn(float(duration_s))
                if not isinstance(value, dict):
                    raise ValueError("base_state_fn must return a mapping")
                rotation = _validate_rotation(value.get(
                    "rotation_current_from_future", np.eye(3)))
                translation = value.get("translation_current_m")
                linear_velocity = value.get("linear_velocity_current_m_s")
                angular_velocity = value.get("angular_velocity_current_rad_s")
                if (translation is None or linear_velocity is None or
                        angular_velocity is None):
                    raise ValueError(
                        "base_state_fn requires translation, linear_velocity, and angular_velocity")
                translation = np.asarray(translation, dtype=float)
                linear_velocity = np.asarray(linear_velocity, dtype=float)
                angular_velocity = np.asarray(angular_velocity, dtype=float)
                if any(x.shape != (3,) or not np.isfinite(x).all()
                       for x in (translation, linear_velocity, angular_velocity)):
                    raise ValueError("base_state_fn returned invalid finite 3D vectors")
                resolved = (rotation, translation, linear_velocity, angular_velocity)
            base_state_cache[cache_key] = resolved
            return tuple(value.copy() for value in resolved)

        if cfg.position_anchored_search:
            from .position_anchored_contact_search_v1 import plan_anchored_events
            return plan_anchored_events(self,q0,qd0,lower,upper,velocity_limits,requested_contact,
                target_state_at,base_state_at,target_metadata_cache,kinematics_fn,kinematics_at_time_fn,evaluator,impact_evaluator)
        # Solve the nominal terminal task in its own future base frame.  Every
        # contact-time candidate below repeats this conversion for its own
        # propagated body pose.
        # Resolve the original time grid first. A rejected nominal event must
        # not suppress legal neighbouring events. No extra times are added.
        legal_times=[]; invalid_times={}
        try:
            target_state_at(requested_contact)
            nominal_valid=True
        except UnreachableImpactTarget as error:
            nominal_valid=False
            invalid_times[str(requested_contact)]=str(error)
        for offset in cfg.contact_time_offsets_s:
            duration=round((requested_contact+float(offset))/cfg.dt_s)*cfg.dt_s
            if not cfg.dt_s <= duration <= cfg.dt_s*(cfg.horizon_steps-1):continue
            try:
                target_state_at(duration)
                legal_times.append(duration)
            except UnreachableImpactTarget as error:
                invalid_times[str(duration)]=str(error)
        if not legal_times:
            self.last_diagnostics={'rejection_counts':{'predicted_outgoing_unreachable':len(invalid_times)},
                                   'invalid_contact_times':invalid_times}
            raise RuntimeError('No allowed contact time has an analytic task target: '+str(invalid_times))
        seed_time=(requested_contact if nominal_valid else min(legal_times,key=lambda t:(round(abs(t-requested_contact),9),t)))
        (nominal_rotation, nominal_translation, nominal_linear_velocity,
         nominal_angular_velocity) = base_state_at(seed_time)
        (nominal_target_position, nominal_target_normal,
         nominal_target_velocity) = target_state_at(seed_time)
        relative_target_position = nominal_rotation.T @ (
            nominal_target_position - nominal_translation)
        target_normal = nominal_rotation.T @ nominal_target_normal
        target_velocity = nominal_rotation.T @ nominal_target_velocity
        active_time=seed_time
        if kinematics_at_time_fn is not None:
            racket_pos,racket_normal,jp,jn=kinematics_fn(q0.copy())
        q_contact = np.asarray(target_metadata_cache.get(round(seed_time,9),{}).get('optimized_q_rad',q0)).copy()
        if kinematics_at_time_fn is not None:
            current_seed=kinematics_fn(q_contact.copy())
        else:current_seed=(racket_pos.copy(),racket_normal.copy(),jp.copy(),jn.copy())
        current_pos,current_normal,current_jp,current_jn=current_seed
        # Without a forward-kinematics callback the supplied Jacobian is the
        # complete linear model, so applying the same correction repeatedly
        # would over-shoot the terminal task.  Re-linearize only when the
        # caller can evaluate the updated configuration.
        iteration_count = cfg.kinematic_iterations if kinematics_fn is not None else 1
        for _ in range(iteration_count):
            current_normal = current_normal / max(np.linalg.norm(current_normal), 1e-12)
            task = np.vstack((current_jp, cfg.normal_weight * current_jn))
            inverse = _damped_inverse(task, cfg.damping)
            position_error = relative_target_position - current_pos
            normal_error = target_normal - current_normal
            q_delta = inverse @ np.r_[position_error, cfg.normal_weight * normal_error]
            q_delta = np.clip(q_delta, -cfg.max_iteration_step_rad,
                              cfg.max_iteration_step_rad)
            q_contact = np.clip(q_contact + q_delta, lower, upper)
            if kinematics_fn is not None:
                values = kinematics_fn(q_contact.copy())
                if not isinstance(values, (tuple, list)) or len(values) != 4:
                    raise ValueError("kinematics_fn must return position, normal, and two Jacobians")
                candidate_position = np.asarray(values[0], dtype=float)
                candidate_normal = np.asarray(values[1], dtype=float)
                candidate_jp = np.asarray(values[2], dtype=float)
                candidate_jn = np.asarray(values[3], dtype=float)
                _validate_vectors(
                    q_contact, np.zeros(6), candidate_jp, candidate_jn,
                    candidate_position, candidate_normal, target_pos,
                    target_normal, target_velocity, base_linear,
                    base_linear_acceleration, base_angular,
                    base_angular_acceleration,
                    racket_offset, lower, upper, velocity_limits)
                current_pos, current_normal = candidate_position, candidate_normal
                current_jp, current_jn = candidate_jp, candidate_jn
        current_normal = current_normal / max(np.linalg.norm(current_normal), 1e-12)
        # The base contributes to the racket point velocity.  Remove it once,
        # matching the moving-base compensation used by the Approach teacher.
        base_point_velocity = nominal_rotation.T @ (
            nominal_linear_velocity + np.cross(
                nominal_angular_velocity, nominal_rotation @ racket_offset))

        # The normal task contains a redundant scalar direction because the
        # racket normal is unit length.  Use that local nullspace to try a few
        # small, deterministic posture offsets.  Each branch is re-evaluated
        # through the real FK callback before it can enter trajectory search;
        # without FK, the supplied linear model remains the single branch.
        branches = [(q_contact.copy(), current_pos.copy(), current_normal.copy(),
                     current_jp.copy(), current_jn.copy(), 0.0, "task")]
        task = np.vstack((current_jp, cfg.normal_weight * current_jn))
        if kinematics_fn is not None and cfg.nullspace_offsets_rad:
            _, singular_values, vh = np.linalg.svd(task, full_matrices=True)
            rank = int(np.sum(singular_values > max(float(singular_values[0]), 1e-12) * 1e-8))
            # The intended case is the regular 5-DOF position-plus-unit-normal
            # task.  If the normal Jacobian is entirely degenerate, keep the
            # caller's original single branch instead of inventing posture
            # alternatives from an underconstrained test task.
            if rank == 5:
                null_direction = vh[rank:].T[:, 0]
                first = np.flatnonzero(np.abs(null_direction) > 1e-9)
                if len(first) and null_direction[first[0]] < 0.0:
                    null_direction = -null_direction
                for offset in cfg.nullspace_offsets_rad:
                    branch_q = np.clip(q_contact + float(offset) * null_direction,
                                       lower, upper)
                    values = kinematics_fn(branch_q.copy())
                    if not isinstance(values, (tuple, list)) or len(values) != 4:
                        raise ValueError("kinematics_fn must return position, normal, and two Jacobians")
                    branch_pos = np.asarray(values[0], dtype=float)
                    branch_normal = np.asarray(values[1], dtype=float)
                    branch_jp = np.asarray(values[2], dtype=float)
                    branch_jn = np.asarray(values[3], dtype=float)
                    _validate_vectors(
                        branch_q, np.zeros(6), branch_jp, branch_jn,
                        branch_pos, branch_normal, target_pos, target_normal,
                        target_velocity, base_linear, base_linear_acceleration,
                        base_angular, base_angular_acceleration, racket_offset,
                        lower, upper, velocity_limits)
                    branches.append((branch_q, branch_pos, branch_normal,
                                     branch_jp, branch_jn, float(offset), "nullspace"))
        # A full position-plus-normal solve can stall near a wrist limit when
        # the desired face direction is temporarily unreachable.  Add one
        # deterministic position-priority branch so the search can still
        # find a physically close contact point; the normal residual remains
        # a hard admission gate below and is never silently discarded.
        if kinematics_fn is not None:
            position_q = q0.copy()
            position_pos, position_normal = racket_pos.copy(), racket_normal.copy()
            position_jp, position_jn = jp.copy(), jn.copy()
            for _ in range(max(2, iteration_count * 2)):
                position_delta = _damped_inverse(position_jp, cfg.damping) @ (
                    relative_target_position - position_pos)
                position_delta = np.clip(position_delta, -cfg.max_iteration_step_rad,
                                         cfg.max_iteration_step_rad)
                position_q = np.clip(position_q + position_delta, lower, upper)
                values = kinematics_fn(position_q.copy())
                position_pos = np.asarray(values[0], dtype=float)
                position_normal = np.asarray(values[1], dtype=float)
                position_jp = np.asarray(values[2], dtype=float)
                position_jn = np.asarray(values[3], dtype=float)
            branches.append((position_q, position_pos, position_normal,
                             position_jp, position_jn, 0.0, "position_priority"))
        maximum_candidate_duration = requested_contact + max(
            (float(x) for x in cfg.contact_time_offsets_s), default=0.0)
        minimum_joint_speed_duration = min(
            float(np.max(np.abs(branch[0] - q0) / velocity_limits))
            for branch in branches
        )
        if maximum_candidate_duration + 1e-9 < minimum_joint_speed_duration:
            self.last_diagnostics = {
                "candidates_considered": 0,
                "accepted_candidates": 0,
                "rejection_counts": {"contact_time_below_joint_speed_bound": 1},
                "evaluator_rejection_reasons": {},
                "minimum_joint_speed_duration_s": minimum_joint_speed_duration,
                "maximum_candidate_duration_s": maximum_candidate_duration,
                "raw_base_linear_acceleration_world_m_s2": raw_base_linear_acceleration.tolist(),
                "used_base_linear_acceleration_world_m_s2": base_linear_acceleration.tolist(),
                "raw_base_angular_acceleration_world_rad_s2": raw_base_angular_acceleration.tolist(),
                "used_base_angular_acceleration_world_rad_s2": base_angular_acceleration.tolist(),
            }
            raise RuntimeError(
                "No contact-first candidate passed pre-contact checks: "
                "contact_time_below_joint_speed_bound"
            )
        best = None
        rejected = []
        evaluator_rejection_reasons = Counter()
        candidates_considered = 0
        accepted_candidates = 0
        best_kinematic_residual = None
        best_kinematic_residual_by_branch = {}
        for (branch_q, branch_pos, branch_normal, branch_jp, branch_jn,
             nullspace_offset, branch_kind) in branches:
            branch_normal = branch_normal / max(np.linalg.norm(branch_normal), 1e-12)
            for offset in cfg.contact_time_offsets_s:
                duration = requested_contact + float(offset)
                if duration < cfg.dt_s or duration > cfg.dt_s * (cfg.horizon_steps - 1):
                    continue
                contact_index = int(round(duration / cfg.dt_s))
                duration = contact_index * cfg.dt_s
                if contact_index < 1 or contact_index >= cfg.horizon_steps:
                    continue
                times = np.arange(contact_index + 1, dtype=float) * cfg.dt_s
                try:
                    candidate_target_pos, candidate_target_normal, candidate_target_velocity = target_state_at(duration)
                except UnreachableImpactTarget:
                    rejected.append('predicted_outgoing_unreachable')
                    continue
                active_time=duration
                if kinematics_at_time_fn is not None:
                    branch_pos,branch_normal,branch_jp,branch_jn=kinematics_fn(branch_q.copy())
                (candidate_rotation, candidate_base_displacement,
                 candidate_linear_velocity, candidate_angular_velocity) = (
                    base_state_at(duration))
                candidate_target_normal = candidate_rotation.T @ candidate_target_normal
                candidate_target_velocity = candidate_rotation.T @ candidate_target_velocity
                nominal_target_normal_for_audit = candidate_target_normal.copy()
                candidate_relative_position = candidate_rotation.T @ (
                    candidate_target_pos - candidate_base_displacement)
                contact_base_point_velocity = candidate_rotation.T @ (
                    candidate_linear_velocity + np.cross(
                        candidate_angular_velocity,
                        candidate_rotation @ racket_offset))
                relative_velocity = candidate_target_velocity - contact_base_point_velocity
                # Select the closest bounded tangent-plane face adjustment for
                # this arm branch. This lets the search trade an unreachable
                # nominal face for a nearby realizable one while retaining a
                # hard residual check on the selected normal.
                tangent_u, tangent_v = _normal_tangent_basis(candidate_target_normal)
                normal_options = []
                for normal_offset in (((0.,0.),) if cfg.inverse_impact_targets else cfg.normal_tangent_offsets_rad):
                    normal_offset = (float(normal_offset[0]), float(normal_offset[1]))
                    adjusted_normal = candidate_target_normal + (
                        normal_offset[0] * tangent_u + normal_offset[1] * tangent_v)
                    adjusted_normal /= max(float(np.linalg.norm(adjusted_normal)), 1e-12)
                    normal_options.append((
                        float(np.linalg.norm(adjusted_normal - branch_normal)),
                        abs(normal_offset[0]) + abs(normal_offset[1]),
                        normal_offset, adjusted_normal))
                _, _, selected_normal_offset, candidate_target_normal = min(
                    normal_options, key=lambda value: (value[0], value[1], value[2]))
                selected_target_normal = candidate_target_normal.copy()
                requested_target_normal = nominal_target_normal_for_audit.copy()
                candidate_q = branch_q.copy()
                if kinematics_fn is None:
                    candidate_pos = racket_pos + jp @ (candidate_q - q0)
                    candidate_normal = racket_normal + jn @ (candidate_q - q0)
                    candidate_normal /= max(np.linalg.norm(candidate_normal), 1e-12)
                else:
                    candidate_pos = branch_pos.copy()
                    candidate_normal = branch_normal.copy()
                candidate_jp = branch_jp.copy()
                candidate_jn = branch_jn.copy()
                # Re-solve the terminal task for each time-varying ball state
                # and its corresponding base displacement.  The correction is
                # bounded and starts from the branch warm start, so the
                # fixed-size search remains deterministic and causal.
                needs_time_resolve = (
                    target_state_fn is not None or
                    base_state_fn is not None or
                    abs(duration - requested_contact) > 1e-9)
                for _ in range((min(2, iteration_count) if kinematics_fn is not None else 1)
                               if needs_time_resolve else 0):
                    candidate_normal = candidate_normal / max(
                        np.linalg.norm(candidate_normal), 1e-12)
                    task = np.vstack((candidate_jp, cfg.normal_weight * candidate_jn))
                    inverse = _damped_inverse(task, cfg.damping)
                    task_error = np.r_[
                        candidate_relative_position - candidate_pos,
                        cfg.normal_weight * (candidate_target_normal - candidate_normal)]
                    candidate_delta = inverse @ task_error
                    candidate_delta = np.clip(candidate_delta,
                                              -cfg.max_iteration_step_rad,
                                              cfg.max_iteration_step_rad)
                    candidate_q = np.clip(candidate_q + candidate_delta, lower, upper)
                    if kinematics_fn is None:
                        candidate_pos = racket_pos + jp @ (candidate_q - q0)
                        candidate_normal = racket_normal + jn @ (candidate_q - q0)
                        candidate_jp, candidate_jn = jp, jn
                    else:
                        values = kinematics_fn(candidate_q.copy())
                        if not isinstance(values, (tuple, list)) or len(values) != 4:
                            raise ValueError("kinematics_fn must return position, normal, and two Jacobians")
                        candidate_pos = np.asarray(values[0], dtype=float)
                        candidate_normal = np.asarray(values[1], dtype=float)
                        candidate_jp = np.asarray(values[2], dtype=float)
                        candidate_jn = np.asarray(values[3], dtype=float)
                if branch_kind == "position_priority" and kinematics_fn is not None:
                    # The position-priority branch is deliberately refined
                    # with a small position-only pass after the face task. It
                    # prevents a reachable contact point from being traded
                    # away solely to chase an overconstrained face normal.
                    for _ in range(min(5, iteration_count)):
                        position_delta = _damped_inverse(candidate_jp, cfg.damping) @ (
                            candidate_relative_position - candidate_pos)
                        position_delta = np.clip(
                            position_delta,
                            -min(cfg.max_iteration_step_rad, 0.12),
                            min(cfg.max_iteration_step_rad, 0.12))
                        candidate_q = np.clip(candidate_q + position_delta, lower, upper)
                        values = kinematics_fn(candidate_q.copy())
                        if not isinstance(values, (tuple, list)) or len(values) != 4:
                            raise ValueError("kinematics_fn must return position, normal, and two Jacobians")
                        candidate_pos = np.asarray(values[0], dtype=float)
                        candidate_normal = np.asarray(values[1], dtype=float)
                        candidate_jp = np.asarray(values[2], dtype=float)
                        candidate_jn = np.asarray(values[3], dtype=float)
                normal_projection = False
                final_candidate_normal = candidate_normal / max(
                    float(np.linalg.norm(candidate_normal)), 1e-12)
                normal_deviation = math.acos(float(np.clip(
                    nominal_target_normal_for_audit @ final_candidate_normal, -1.0, 1.0)))
                if (not cfg.inverse_impact_targets and cfg.adaptive_normal_target_max_deviation_rad > 0.0 and
                        normal_deviation <= cfg.adaptive_normal_target_max_deviation_rad):
                    # The final position-refined arm state supplies a nearby
                    # face orientation.  Admit it only inside the explicit
                    # deviation bound, and retain the original normal in the
                    # audit so this adaptation cannot hide a large re-aim.
                    candidate_target_normal = final_candidate_normal.copy()
                    normal_projection = True
                inverse = _damped_inverse(
                    np.vstack((candidate_jp, cfg.normal_weight * candidate_jn)), cfg.damping)
                qd_contact_nominal = inverse @ np.r_[relative_velocity,
                                                     cfg.normal_weight * cfg.normal_rate_gain *
                                                     (candidate_target_normal - candidate_normal)]
                qd_contact_nominal = np.clip(qd_contact_nominal, -velocity_limits,
                                             velocity_limits)
                if cfg.inverse_impact_targets:
                    from scipy.optimize import lsq_linear
                    matrix=np.vstack((candidate_jp,cfg.normal_weight*candidate_jn,
                                      cfg.damping*np.eye(6)))
                    rhs=np.r_[relative_velocity,cfg.normal_weight*cfg.normal_rate_gain*
                              (candidate_target_normal-candidate_normal),np.zeros(6)]
                    fit=lsq_linear(matrix,rhs,bounds=(-velocity_limits,velocity_limits),max_iter=50)
                    if not fit.success:
                        rejected.append('bounded_task_velocity_solve_failed')
                        continue
                    qd_contact_nominal=fit.x
                for velocity_scale in ((1.,) if cfg.inverse_impact_targets else cfg.velocity_scales):
                    candidates_considered += 1
                    qd1 = np.clip(qd_contact_nominal * float(velocity_scale),
                                  -velocity_limits, velocity_limits)
                    q_prefix, qd_prefix = _hermite(q0, qd0, candidate_q, qd1,
                                               duration, times)
                    q_full = np.broadcast_to(candidate_q, (cfg.horizon_steps, 6)).copy()
                    qd_full = np.zeros_like(q_full)
                    q_full[:contact_index + 1] = q_prefix
                    qd_full[:contact_index + 1] = qd_prefix
                    step_limit = velocity_limits * cfg.dt_s + 1e-9
                    if np.any(np.abs(np.diff(q_full, axis=0)) > step_limit):
                        rejected.append("joint_step_limit")
                        continue
                    # The endpoint velocity is clipped above, but a cubic Hermite
                    # prefix can still overshoot between its endpoints.  Reject
                    # that candidate before scoring it so the search never
                    # selects a trajectory that violates its own six-joint speed
                    # contract between sampled contact nodes.
                    if np.any(np.abs(qd_prefix) > velocity_limits[None, :] + 1e-9):
                        rejected.append("trajectory_velocity_limit")
                        continue
                    achieved_velocity = contact_base_point_velocity + candidate_jp @ qd1
                    requested_velocity_error = float(np.linalg.norm(
                        candidate_target_velocity - achieved_velocity))
                    effective_target_velocity = candidate_target_velocity.copy()
                    velocity_projection = False
                    if requested_velocity_error > cfg.velocity_tolerance_m_s:
                        projected_relative = achieved_velocity - contact_base_point_velocity
                        requested_relative = candidate_target_velocity - contact_base_point_velocity
                        projected_norm = float(np.linalg.norm(projected_relative))
                        requested_norm = float(np.linalg.norm(requested_relative))
                        alignment = (float(projected_relative @ requested_relative) /
                                     max(projected_norm * requested_norm, 1e-12))
                        if (cfg.allow_reachable_velocity_projection and
                                float(np.linalg.norm(achieved_velocity)) >=
                                cfg.minimum_contact_speed_m_s and
                                alignment >= cfg.minimum_contact_speed_alignment):
                            # Keep the original requested velocity in the
                            # audit, but admit the actually reachable nonzero
                            # contact velocity as the selected event target.
                            effective_target_velocity = achieved_velocity.copy()
                            velocity_projection = True
                        else:
                            rejected.append("velocity_unreachable")
                            continue
                    if float(np.linalg.norm(achieved_velocity)) < cfg.minimum_contact_speed_m_s:
                        rejected.append("zero_contact_speed")
                        continue
