"""Deterministic contact-first trajectory search for jump-and-hit motion.

This module is a small, causal planner for the Approach teacher.  It follows
the useful part of the ball-bumping formulation in arXiv:2210.05195: solve a
time/state terminal condition for the hit first, then let the existing
whole-body controller track that reference.  It deliberately does not search
the landing phase.

The planner is kinematic at the arm level.  A caller may attach the existing
full-body predictor as ``evaluator``; a candidate is executable only when that
evaluator accepts the complete pre-contact prefix.  No TRAIN case, future
trajectory, or learned action is used here.
"""
from dataclasses import dataclass
from collections import Counter
import math
from typing import Callable, Optional

import numpy as np


@dataclass(frozen=True)
class ContactFirstSearchConfig:
    """Bounded deterministic candidate contract.

    The small grid searches contact timing and contact-speed scale, while the
    six-joint increments are generated by the measured racket Jacobian.  The
    suffix after contact is a held endpoint and is not part of contact-first
    acceptance.
    """

    dt_s: float = 0.01
    # Approach planning starts around t=2.0 s while contact is commonly near
    # 2.7 s in the current DTG contract; 96 x 10 ms covers that interval.
    # Recovery's independent 32-node protocol is unchanged.
    horizon_steps: int = 96
    contact_time_offsets_s: tuple = (-0.02, 0.0, 0.02)
    velocity_scales: tuple = (0.8, 1.0, 1.2)
    # The racket normal has only two independent orientation coordinates, so a
    # six-joint arm normally retains one local nullspace direction.  Exploring
    # a few bounded posture offsets lets the same contact task use a less
    # saturated joint without changing the task target or physical limits.
    nullspace_offsets_rad: tuple = (-0.12, -0.06, 0.06, 0.12)
    damping: float = 0.04
    normal_weight: float = 0.30
    normal_rate_gain: float = 2.0
    arm_velocity_limit_rad_s: float = 5.0
    # Five bounded re-linearizations materially improve nonlinear FK
    # convergence while remaining sub-2 ms on the CPU benchmark path.
    kinematic_iterations: int = 5
    max_iteration_step_rad: float = 0.25
    handoff_duration_s: float = 0.02
    position_tolerance_m: float = 0.035
    normal_tolerance: float = 0.12
    velocity_tolerance_m_s: float = 0.75

    def validate(self):
        if not math.isfinite(self.dt_s) or self.dt_s <= 0.0:
            raise ValueError("Positive planner timestep required")
        if self.horizon_steps < 2:
            raise ValueError("At least two trajectory nodes required")
        for name in ("contact_time_offsets_s", "velocity_scales", "nullspace_offsets_rad"):
            values = tuple(float(x) for x in getattr(self, name))
            if name != "nullspace_offsets_rad" and not values:
                raise ValueError(f"Finite {name} required")
            if not all(math.isfinite(x) for x in values):
                raise ValueError(f"Finite {name} required")
        if self.damping <= 0.0 or self.normal_weight <= 0.0:
            raise ValueError("Positive task damping and normal weight required")
        if not math.isfinite(self.arm_velocity_limit_rad_s) or self.arm_velocity_limit_rad_s <= 0.0:
            raise ValueError("Positive arm velocity limit required")
        if self.kinematic_iterations < 1 or self.kinematic_iterations > 8:
            raise ValueError("Kinematic iterations must be in [1, 8]")
        if not math.isfinite(self.max_iteration_step_rad) or self.max_iteration_step_rad <= 0.0:
            raise ValueError("Positive kinematic iteration step required")
        if not math.isfinite(self.handoff_duration_s) or not 0.0 <= self.handoff_duration_s <= 0.2:
            raise ValueError("Handoff duration must be in [0, 0.2] seconds")
        return self


@dataclass(frozen=True)
class BallisticContactEvent:
    time_s: float
    position_world_m: np.ndarray
    velocity_world_m_s: np.ndarray


@dataclass
class ContactFirstCandidate:
    """A candidate arm trajectory and its contact-prefix diagnostics."""

    q_rad: np.ndarray
    qd_rad_s: np.ndarray
    contact_index: int
    contact_time_s: float
    score: float
    position_error_m: float
    normal_error: float
    velocity_error_m_s: float
    metadata: dict


def solve_ballistic_plane_contact(position_world_m, velocity_world_m_s,
                                  plane_point_world_m, plane_normal_world,
                                  gravity_world=(0.0, 0.0, -9.81),
                                  min_time_s=0.0, max_time_s=2.0):
    """Solve the first descending ballistic crossing of a contact plane.

    DTG's existing drag-aware ``predict_initial_intercept`` remains the
    preferred production event source.  This helper supplies the paper-style
    low-cost time/state fallback and is useful for CPU validation.
    """
    p = np.asarray(position_world_m, dtype=float)
    v = np.asarray(velocity_world_m_s, dtype=float)
    plane = np.asarray(plane_point_world_m, dtype=float)
    normal = np.asarray(plane_normal_world, dtype=float)
    gravity = np.asarray(gravity_world, dtype=float)
    if any(x.shape != (3,) for x in (p, v, plane, normal, gravity)):
        raise ValueError("Ballistic contact vectors must be 3D")
    if not all(np.isfinite(x).all() for x in (p, v, plane, normal, gravity)):
        raise ValueError("Finite ballistic contact vectors required")
    norm = np.linalg.norm(normal)
    if norm < 1e-9:
        raise ValueError("Nonzero contact-plane normal required")
    normal = normal / norm
    c = float(normal @ (p - plane))
    b = float(normal @ v)
    a = 0.5 * float(normal @ gravity)
    if abs(a) < 1e-10:
        roots = [] if abs(b) < 1e-10 else [-c / b]
    else:
        discriminant = b * b - 4.0 * a * c
        if discriminant < 0.0:
            return None
        root = math.sqrt(max(discriminant, 0.0))
        roots = [(-b - root) / (2.0 * a), (-b + root) / (2.0 * a)]
    roots = sorted(t for t in roots if min_time_s <= t <= max_time_s)
    for time_s in roots:
        velocity = v + gravity * time_s
        # Descending means motion is toward the negative normal side at hit.
        if float(normal @ velocity) <= 0.0:
            return BallisticContactEvent(
                time_s=float(time_s),
                position_world_m=p + v * time_s + 0.5 * gravity * time_s * time_s,
                velocity_world_m_s=velocity,
            )
    return None


def _validate_vectors(q, qd, position_jacobian, normal_jacobian,
                      racket_position, racket_normal, target_position,
                      target_normal, target_velocity, base_linear_velocity,
                      base_angular_velocity, racket_offset, lower, upper,
                      velocity_limits):
    q = np.asarray(q, dtype=float)
    qd = np.asarray(qd, dtype=float)
    jp = np.asarray(position_jacobian, dtype=float)
    jn = np.asarray(normal_jacobian, dtype=float)
    vectors = [racket_position, racket_normal, target_position, target_normal,
               target_velocity, base_linear_velocity, base_angular_velocity,
               racket_offset]
    vectors = [np.asarray(x, dtype=float) for x in vectors]
    lower = np.asarray(lower, dtype=float)
    upper = np.asarray(upper, dtype=float)
    velocity_limits = np.asarray(velocity_limits, dtype=float)
    if q.shape != (6,) or qd.shape != (6,):
        raise ValueError("Six arm joint positions and velocities required")
    if jp.shape != (3, 6) or jn.shape != (3, 6):
        raise ValueError("Position and normal Jacobians must be 3x6")
    if any(x.shape != (3,) for x in vectors):
        raise ValueError("Contact vectors must be 3D")
    if lower.shape != (6,) or upper.shape != (6,) or velocity_limits.shape != (6,):
        raise ValueError("Six-joint bounds and velocity limits required")
    if np.any(upper <= lower) or np.any(velocity_limits <= 0.0):
        raise ValueError("Strict joint and velocity bounds required")
    if not all(np.isfinite(x).all() for x in [q, qd, jp, jn, *vectors,
                                               lower, upper, velocity_limits]):
        raise ValueError("Finite contact search inputs required")
    return (q, qd, jp, jn, *vectors, lower, upper, velocity_limits)


def _damped_inverse(matrix, damping):
    return matrix.T @ np.linalg.solve(matrix @ matrix.T + damping * damping *
                                      np.eye(matrix.shape[0]), np.eye(matrix.shape[0]))


def _hermite(q0, qd0, q1, qd1, duration_s, times_s):
    s = np.clip(np.asarray(times_s, dtype=float) / duration_s, 0.0, 1.0)
    h00 = 2.0 * s**3 - 3.0 * s**2 + 1.0
    h10 = s**3 - 2.0 * s**2 + s
    h01 = -2.0 * s**3 + 3.0 * s**2
    h11 = s**3 - s**2
    q = (h00[:, None] * q0 + h10[:, None] * duration_s * qd0 +
         h01[:, None] * q1 + h11[:, None] * duration_s * qd1)
    dh00 = 6.0 * s**2 - 6.0 * s
    dh10 = 3.0 * s**2 - 4.0 * s + 1.0
    dh01 = -6.0 * s**2 + 6.0 * s
    dh11 = 3.0 * s**2 - 2.0 * s
    qd = (dh00[:, None] * q0 + dh10[:, None] * duration_s * qd0 +
          dh01[:, None] * q1 + dh11[:, None] * duration_s * qd1) / duration_s
    return q, qd


class ContactFirstTrajectorySearchV1:
    """Low-dimensional, deterministic contact-prefix search.

    ``evaluator`` receives ``(q_rad, qd_rad_s, contact_index, metadata)`` and
    must return either ``True`` or a mapping with ``accepted``.  It should use
    the existing full-body predictor when available.  Without an evaluator,
    this class performs only the causal kinematic and actuator precheck.
    """

    def __init__(self, config=None):
        self.config = (config or ContactFirstSearchConfig()).validate()
        self.last_diagnostics = {}

    def plan(self, *, q_rad, qd_rad_s, position_jacobian, normal_jacobian,
             racket_position_world_m, racket_normal_world,
             target_position_world_m, target_normal_world, target_velocity_world_m_s,
             contact_time_s, base_linear_velocity_world_m_s=(0.0, 0.0, 0.0),
             base_angular_velocity_world_rad_s=(0.0, 0.0, 0.0),
             racket_offset_world_m=(0.0, 0.0, 0.0), lower_rad, upper_rad,
             velocity_limits_rad_s, evaluator: Optional[Callable] = None,
             kinematics_fn: Optional[Callable] = None):
        data = _validate_vectors(
            q_rad, qd_rad_s, position_jacobian, normal_jacobian,
            racket_position_world_m, racket_normal_world,
            target_position_world_m, target_normal_world,
            target_velocity_world_m_s, base_linear_velocity_world_m_s,
            base_angular_velocity_world_rad_s, racket_offset_world_m,
            lower_rad, upper_rad, velocity_limits_rad_s)
        (q0, qd0, jp, jn, racket_pos, racket_normal, target_pos,
         target_normal, target_velocity, base_linear, base_angular,
         racket_offset, lower, upper, velocity_limits) = data
        cfg = self.config
        racket_normal = racket_normal / max(np.linalg.norm(racket_normal), 1e-12)
        target_normal = target_normal / max(np.linalg.norm(target_normal), 1e-12)
        q_contact = q0.copy()
        current_pos, current_normal = racket_pos.copy(), racket_normal.copy()
        current_jp, current_jn = jp.copy(), jn.copy()
        # Without a forward-kinematics callback the supplied Jacobian is the
        # complete linear model, so applying the same correction repeatedly
        # would over-shoot the terminal task.  Re-linearize only when the
        # caller can evaluate the updated configuration.
        iteration_count = cfg.kinematic_iterations if kinematics_fn is not None else 1
        for _ in range(iteration_count):
            current_normal = current_normal / max(np.linalg.norm(current_normal), 1e-12)
            task = np.vstack((current_jp, cfg.normal_weight * current_jn))
            inverse = _damped_inverse(task, cfg.damping)
            position_error = target_pos - current_pos
            normal_error = target_normal - current_normal
            q_delta = inverse @ np.r_[position_error, cfg.normal_weight * normal_error]
            q_delta = np.clip(q_delta, -cfg.max_iteration_step_rad,
                              cfg.max_iteration_step_rad)
            q_contact = np.clip(q_contact + q_delta, lower, upper)
            if kinematics_fn is not None:
                values = kinematics_fn(q_contact.copy())
                if not isinstance(values, (tuple, list)) or len(values) != 4:
                    raise ValueError("kinematics_fn must return position, normal, and two Jacobians")
                candidate_position = np.asarray(values[0], dtype=float)
                candidate_normal = np.asarray(values[1], dtype=float)
                candidate_jp = np.asarray(values[2], dtype=float)
                candidate_jn = np.asarray(values[3], dtype=float)
                _validate_vectors(
                    q_contact, np.zeros(6), candidate_jp, candidate_jn,
                    candidate_position, candidate_normal, target_pos,
                    target_normal, target_velocity, base_linear, base_angular,
                    racket_offset, lower, upper, velocity_limits)
                current_pos, current_normal = candidate_position, candidate_normal
                current_jp, current_jn = candidate_jp, candidate_jn
        current_normal = current_normal / max(np.linalg.norm(current_normal), 1e-12)
        # The base contributes to the racket point velocity.  Remove it once,
        # matching the moving-base compensation used by the Approach teacher.
        base_point_velocity = base_linear + np.cross(base_angular, racket_offset)
        relative_velocity = target_velocity - base_point_velocity

        # The normal task contains a redundant scalar direction because the
        # racket normal is unit length.  Use that local nullspace to try a few
        # small, deterministic posture offsets.  Each branch is re-evaluated
        # through the real FK callback before it can enter trajectory search;
        # without FK, the supplied linear model remains the single branch.
        branches = [(q_contact.copy(), current_pos.copy(), current_normal.copy(),
                     current_jp.copy(), current_jn.copy(), 0.0)]
        task = np.vstack((current_jp, cfg.normal_weight * current_jn))
        if kinematics_fn is not None and cfg.nullspace_offsets_rad:
            _, singular_values, vh = np.linalg.svd(task, full_matrices=True)
            rank = int(np.sum(singular_values > max(float(singular_values[0]), 1e-12) * 1e-8))
            # The intended case is the regular 5-DOF position-plus-unit-normal
            # task.  If the normal Jacobian is entirely degenerate, keep the
            # caller's original single branch instead of inventing posture
            # alternatives from an underconstrained test task.
            if rank == 5:
                null_direction = vh[rank:].T[:, 0]
                first = np.flatnonzero(np.abs(null_direction) > 1e-9)
                if len(first) and null_direction[first[0]] < 0.0:
                    null_direction = -null_direction
                for offset in cfg.nullspace_offsets_rad:
                    branch_q = np.clip(q_contact + float(offset) * null_direction,
                                       lower, upper)
                    values = kinematics_fn(branch_q.copy())
                    if not isinstance(values, (tuple, list)) or len(values) != 4:
                        raise ValueError("kinematics_fn must return position, normal, and two Jacobians")
                    branch_pos = np.asarray(values[0], dtype=float)
                    branch_normal = np.asarray(values[1], dtype=float)
                    branch_jp = np.asarray(values[2], dtype=float)
                    branch_jn = np.asarray(values[3], dtype=float)
                    _validate_vectors(
                        branch_q, np.zeros(6), branch_jp, branch_jn,
                        branch_pos, branch_normal, target_pos, target_normal,
                        target_velocity, base_linear, base_angular, racket_offset,
                        lower, upper, velocity_limits)
                    branches.append((branch_q, branch_pos, branch_normal,
                                     branch_jp, branch_jn, float(offset)))
        requested_contact = float(contact_time_s)
        if not math.isfinite(requested_contact) or requested_contact <= cfg.dt_s:
            raise ValueError("Positive contact time after current state required")
        maximum_candidate_duration = requested_contact + max(
            (float(x) for x in cfg.contact_time_offsets_s), default=0.0)
        minimum_joint_speed_duration = min(
            float(np.max(np.abs(branch[0] - q0) / velocity_limits))
            for branch in branches
        )
        if maximum_candidate_duration + 1e-9 < minimum_joint_speed_duration:
            self.last_diagnostics = {
                "candidates_considered": 0,
                "accepted_candidates": 0,
                "rejection_counts": {"contact_time_below_joint_speed_bound": 1},
                "evaluator_rejection_reasons": {},
                "minimum_joint_speed_duration_s": minimum_joint_speed_duration,
                "maximum_candidate_duration_s": maximum_candidate_duration,
            }
            raise RuntimeError(
                "No contact-first candidate passed pre-contact checks: "
                "contact_time_below_joint_speed_bound"
            )
        best = None
        rejected = []
        evaluator_rejection_reasons = Counter()
        candidates_considered = 0
        accepted_candidates = 0
        for branch_q, branch_pos, branch_normal, branch_jp, branch_jn, nullspace_offset in branches:
            branch_normal = branch_normal / max(np.linalg.norm(branch_normal), 1e-12)
            task = np.vstack((branch_jp, cfg.normal_weight * branch_jn))
            inverse = _damped_inverse(task, cfg.damping)
            normal_error = target_normal - branch_normal
            normal_rate = cfg.normal_rate_gain * normal_error
            qd_contact_nominal = inverse @ np.r_[relative_velocity,
                                                 cfg.normal_weight * normal_rate]
            qd_contact_nominal = np.clip(qd_contact_nominal, -velocity_limits,
                                         velocity_limits)
            for offset in cfg.contact_time_offsets_s:
                duration = requested_contact + float(offset)
                if duration < cfg.dt_s or duration > cfg.dt_s * (cfg.horizon_steps - 1):
                    continue
                contact_index = int(round(duration / cfg.dt_s))
                duration = contact_index * cfg.dt_s
                if contact_index < 1 or contact_index >= cfg.horizon_steps:
                    continue
                times = np.arange(contact_index + 1, dtype=float) * cfg.dt_s
                for velocity_scale in cfg.velocity_scales:
                    candidates_considered += 1
                    qd1 = np.clip(qd_contact_nominal * float(velocity_scale),
                                  -velocity_limits, velocity_limits)
                    q_prefix, qd_prefix = _hermite(q0, qd0, branch_q, qd1,
                                               duration, times)
                    q_full = np.broadcast_to(branch_q, (cfg.horizon_steps, 6)).copy()
                    qd_full = np.zeros_like(q_full)
                    q_full[:contact_index + 1] = q_prefix
                    qd_full[:contact_index + 1] = qd_prefix
                    step_limit = velocity_limits * cfg.dt_s + 1e-9
                    if np.any(np.abs(np.diff(q_full, axis=0)) > step_limit):
                        rejected.append("joint_step_limit")
                        continue
                    # The endpoint velocity is clipped above, but a cubic Hermite
                    # prefix can still overshoot between its endpoints.  Reject
                    # that candidate before scoring it so the search never
                    # selects a trajectory that violates its own six-joint speed
                    # contract between sampled contact nodes.
                    if np.any(np.abs(qd_prefix) > velocity_limits[None, :] + 1e-9):
                        rejected.append("trajectory_velocity_limit")
                        continue
                    metadata = dict(
                    method="dtg_contact_first_hermite_jacobian_v1",
                    contact_index=contact_index,
                    contact_time_s=duration,
                    velocity_scale=float(velocity_scale),
                    nullspace_offset_rad=float(nullspace_offset),
                    initial_joint_position_rad=q0.copy(),
                    initial_joint_velocity_rad_s=qd0.copy(),
                    base_point_velocity_world_m_s=base_point_velocity.copy(),
                    relative_target_velocity_world_m_s=relative_velocity.copy(),
                    source="causal_ball_or_dtg_contact_event",
                )
                    # Linearized terminal diagnostics are deliberately separate
                    # from the physical evaluator and never replace it.  Run
                    # this cheap gate first so expensive full-body replay is
                    # only spent on candidates that satisfy the causal task
                    # residual contract.
                    if kinematics_fn is None:
                        achieved_pos = racket_pos + jp @ (branch_q - q0)
                        achieved_normal = racket_normal + jn @ (branch_q - q0)
                        achieved_normal /= max(np.linalg.norm(achieved_normal), 1e-12)
                        achieved_jp = jp
                    else:
                        achieved_pos, achieved_normal = branch_pos, branch_normal
                        achieved_jp = branch_jp
                    achieved_velocity = base_point_velocity + achieved_jp @ qd1
                    position_error_norm = float(np.linalg.norm(target_pos - achieved_pos))
                    normal_error_norm = float(np.linalg.norm(target_normal - achieved_normal))
                    velocity_error_norm = float(np.linalg.norm(target_velocity - achieved_velocity))
                    if (position_error_norm > cfg.position_tolerance_m or
                            normal_error_norm > cfg.normal_tolerance or
                            velocity_error_norm > cfg.velocity_tolerance_m_s):
                        rejected.append("kinematic_task_residual")
                        continue
                    accepted = True
                    evaluator_result = None
                    if evaluator is not None:
                        evaluator_result = evaluator(q_full, qd_full, contact_index,
                                                     metadata)
                        accepted = bool(evaluator_result if isinstance(evaluator_result, (bool, np.bool_))
                                        else evaluator_result.get("accepted", False))
                    if not accepted:
                        rejected.append("evaluator")
                        if isinstance(evaluator_result, dict):
                            reason = evaluator_result.get("rejection", "unspecified")
                            evaluator_rejection_reasons[str(reason)] += 1
                        continue
                    score = (position_error_norm / cfg.position_tolerance_m +
                             normal_error_norm / cfg.normal_tolerance +
                             velocity_error_norm / cfg.velocity_tolerance_m_s +
                             0.02 * float(np.linalg.norm(qd1)) +
                             1e-6 * contact_index)
                    accepted_candidates += 1
                    candidate = ContactFirstCandidate(
                        q_rad=q_full, qd_rad_s=qd_full,
                        contact_index=contact_index, contact_time_s=duration,
                        score=float(score), position_error_m=position_error_norm,
                        normal_error=normal_error_norm,
                        velocity_error_m_s=velocity_error_norm,
                        metadata=dict(metadata,
                                      kinematic_iterations=iteration_count,
                                      evaluator=evaluator_result,
                                      rejected_before_selection=tuple(rejected)))
                    if best is None or candidate.score < best.score:
                        best = candidate
        self.last_diagnostics = {
            "candidates_considered": candidates_considered,
            "accepted_candidates": accepted_candidates,
            "rejection_counts": dict(Counter(rejected)),
            "evaluator_rejection_reasons": dict(evaluator_rejection_reasons),
        }
        if best is None:
            raise RuntimeError(
                "No contact-first candidate passed pre-contact checks: "
                f"{self.last_diagnostics['rejection_counts']}"
            )
        best.metadata["search_diagnostics"] = dict(self.last_diagnostics)
        return best


