"""Combine end-checked model candidates without changing their trajectories.

This only accepts libraries already generated by the end-observation merge.
It adds no expert/native-success label and does not claim a combined policy
has been executed. Causal matching and full-controller checks remain needed.
"""
import argparse
import hashlib
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--libraries', type=Path, nargs='+', required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()
    if args.output.exists():
        raise ValueError('Immutable new library required')
    pins = {str(Path(__file__).resolve()):sha(__file__)}
    references, keys = [], set()
    for path in args.libraries:
        library = json.loads(path.read_text())
        if (library['schema'] != 'model-recovery-reference-library-v2' or
                library['control_dt_s'] != .01 or library['native_success'] or
                library['valid_expert_labels'] or library['training']):
            raise ValueError('Compatible model-only library required')
        for filename,digest in library['source_sha256'].items():
            if sha(filename) != digest or (filename in pins and pins[filename] != digest):
                raise ValueError('Changed/conflicting library source '+filename)
            pins[filename] = digest
        for row in library['references']:
            # A finite optimized reference may be followed by sustained
            # feedback. Require that full executed model feedback reaches the
            # original endpoint; do not confuse reference length with runtime.
            feedback_path = Path(row['source_feedback'])
            if pins.get(str(feedback_path.resolve())) != sha(feedback_path):
                raise ValueError('Unpinned model feedback')
            feedback = json.loads(feedback_path.read_text())
            required = 800-row['source_actual_tick']
            if (row.get('model_end_observation_stable_s', 0.) < .8 or
                    row['native_success'] or row['valid_expert_labels'] or
                    not 1 <= len(row['trajectory']) <= required or
                    feedback['failure'] is not None or feedback['steps'] != required or
                    feedback['trajectory'][-1]['tick'] != 799 or
                    feedback['native_success'] or feedback['valid_expert_labels']):
                raise ValueError('Missing original episode-end model evidence')
            if row['source_key'] in keys:
                raise ValueError('Duplicate candidate')
            keys.add(row['source_key'])
            references.append(row)
        pins[str(path.resolve())] = sha(path)
    output = dict(schema='model-recovery-reference-library-v2', control_dt_s=.01,
        references=references, source_sha256=pins, native_success=False,
        valid_expert_labels=False, training=False,
        full_model_feedback_is_not_native_certification=True)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(output, indent=2, allow_nan=False)+'\n')
    print(json.dumps(dict(model_candidates=len(references),
        source_cases=[r['source_case'] for r in references], native_success=False)))


if __name__ == '__main__':
    main()
